def seed_sentences(db) -> int:
    count = 0
    for text in SAMPLE_SENTENCES:
        exists = db.query(Sentence).filter(Sentence.text == text).first()
        if not exists:
            db.add(Sentence(text=text))
            count += 1
    db.commit()
    return count


def seed_admin(db) -> bool:
    exists = db.query(User).filter(User.username == "admin").first()
    if exists:
        return False
    admin = User(
        username="admin",
        password_hash=hash_password("Admin1234!"),
        name="관리자",
        email="admin@voicecollect.com",
        gender=GenderEnum.other,
        age_group=AgeGroupEnum.thirties,
        region="서울특별시",
        dialect=DialectEnum.standard,
        is_admin=True,
        privacy_agreed=True,
    )
    db.add(admin)
    db.commit()
    return True


def main():
    db = SessionLocal()
    try:
        sentence_count = seed_sentences(db)
        admin_created = seed_admin(db)
        print(f"[seed] 문장 {sentence_count}개 추가 완료 (전체: {len(SAMPLE_SENTENCES)}개)")
        print(f"[seed] 어드민 계정: {'생성 완료 (admin / Admin1234!)' if admin_created else '이미 존재함'}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
